/**
 * Look up benefits by title — fuzzy match against titleMatches array
 */
export function findBenefitsByTitle(title: string): ContentBenefits | null {
  const lower = title.toLowerCase();
  return (
    contentBenefitsData.find((entry) =>
      entry.titleMatches.some(
        (match) =>
          lower.includes(match.toLowerCase()) ||
          match.toLowerCase().includes(lower),
      ),
    ) ?? null
  );
}
