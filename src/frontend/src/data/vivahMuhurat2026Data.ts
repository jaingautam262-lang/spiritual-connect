/**
 * Adjust a time string like "11:32 AM" or "3:45 PM" by offsetMinutes.
 * Positive offset = earlier (city is west of Delhi → sun rises later → times shift forward).
 * Returns adjusted time string in 12-hour format.
 */
export function adjustTimeByOffset(
  timeStr: string,
  offsetMinutes: number,
): string {
  if (!timeStr || offsetMinutes === 0) return timeStr;
  const match = timeStr.match(/^(\d{1,2}):(\d{2})\s*(AM|PM)$/i);
  if (!match) return timeStr;

  let hours = Number.parseInt(match[1], 10);
  const minutes = Number.parseInt(match[2], 10);
  const period = match[3].toUpperCase();

  // Convert to 24h
  let totalMinutes =
    (period === "PM" && hours !== 12
      ? hours + 12
      : period === "AM" && hours === 12
        ? 0
        : hours) *
      60 +
    minutes;
  totalMinutes += offsetMinutes;

  // Clamp to 0-1439
  totalMinutes = ((totalMinutes % 1440) + 1440) % 1440;

  const h24 = Math.floor(totalMinutes / 60);
  const m = totalMinutes % 60;
  const ampm = h24 < 12 ? "AM" : "PM";
  const h12 = h24 % 12 === 0 ? 12 : h24 % 12;
  return `${h12}:${m.toString().padStart(2, "0")} ${ampm}`;
}

