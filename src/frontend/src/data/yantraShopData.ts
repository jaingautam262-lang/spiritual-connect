import type { Product } from "../types/backend-types";

// ─── Extended Yantra Product Type ─────────────────────────────────────────────
// We don't extend Product directly because Product.benefits is `string`
// but we need string[] here. We compose instead.
export interface YantraProduct {
  // Core fields matching Product for cart compatibility
  id: string;
  name: string;
  category: string;
  price: number;
  description: string;
  astrologicalPurpose: string;
  stock: bigint;
  createdAt: bigint;
  // Extended bilingual fields
  nameHi: string;
  descriptionHi: string;
  subcategory: string;
  material: string;
  size: string;
  originalPrice?: number;
  inStock: boolean;
  imageUrl: string;
  sku: string;
  benefits: string[];
  benefitsHi: string[];
  howToUse: string;
  howToUseHi: string;
  mantra?: string;
}

// Helper to convert for use where Product type is needed
export function yantraAsProduct(y: YantraProduct): Product {
  return {
    id: y.id,
    name: y.name,
    category: y.category,
    price: y.price,
    description: y.description,
    benefits: y.benefits.join("; "),
    astrologicalPurpose: y.astrologicalPurpose,
    stock: y.stock,
    createdAt: y.createdAt,
  };
}

type YantraCategory =
  | "puja-yantra"
  | "hanging-yantra"
  | "chowki-yantra"
  | "frame-yantra";

function makeYantra(
  id: string,
  name: string,
  nameHi: string,
  categorySlug: YantraCategory,
  subcategory: string,
  material: string,
  size: string,
  price: number,
  sku: string,
  benefits: string[],
  benefitsHi: string[],
  howToUse: string,
  howToUseHi: string,
  inStock = true,
  originalPrice?: number,
  mantra?: string,
): YantraProduct {
  const categoryLabel =
    categorySlug === "puja-yantra"
      ? "Puja Yantra"
      : categorySlug === "hanging-yantra"
        ? "Hanging Yantra"
        : categorySlug === "chowki-yantra"
          ? "Chowki Yantra"
          : "Frame Yantra";
  return {
    id,
    name,
    nameHi,
    category: categoryLabel,
    price,
    description: `${name} — ${material}, Size ${size}. A Prana-Pratisthit Siddha Yantra for ${subcategory} blessings.`,
    descriptionHi: `${nameHi} — ${material}, आकार ${size}। ${subcategory} की कृपा के लिए पूर्ण प्राण-प्रतिष्ठित सिद्ध यंत्र।`,
    subcategory,
    material,
    size,
    benefits,
    benefitsHi,
    astrologicalPurpose: subcategory,
    stock: BigInt(inStock ? 50 : 0),
    createdAt: BigInt(0),
    inStock,
    originalPrice,
    imageUrl: "/placeholder-yantra.jpg",
    sku,
    howToUse,
    howToUseHi,
    mantra,
  };
}

